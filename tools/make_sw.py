#!/usr/bin/env python3
"""Generate sw.js for Simply Budgets.

Run this after every change, from the repository root:
    python3 tools/make_sw.py

It lists every file the app needs and builds the cache version from their
contents, so any change produces a new version and installed phones update.
The receipt reader in vendor/ is large, so it is cached the first time a
receipt is scanned instead of on install.
"""
import hashlib, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {".git", ".github", "tools", "brand"}
SKIP_FILES = {"sw.js", "README.md", ".nojekyll", ".DS_Store"}
LAZY_DIRS = {"vendor"}

files, digest = [], hashlib.sha256()
for dirpath, dirnames, filenames in os.walk(ROOT):
    rel_dir = os.path.relpath(dirpath, ROOT)
    top = rel_dir.split(os.sep)[0]
    dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
    if top in SKIP_DIRS:
        continue
    for name in sorted(filenames):
        if name in SKIP_FILES or name.endswith(".md") and top != "vendor":
            continue
        path = os.path.join(dirpath, name)
        rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
        with open(path, "rb") as fh:
            data = fh.read()
        digest.update(rel.encode() + b"\0" + data)
        if top not in LAZY_DIRS:
            files.append("./" + rel)

version = "simply-budgets-" + digest.hexdigest()[:12]
shell = ",\n  ".join('"%s"' % f for f in ["./"] + files)

sw = """// Generated by tools/make_sw.py. Do not edit by hand.
// The version comes from the app's file contents, so every change reaches installed phones.
const CACHE = "%s";
const SHELL = [
  %s
];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)));
});

// The page asks for this when the person taps Update.
self.addEventListener("message", (e) => { if (e.data === "skipWaiting") self.skipWaiting(); });

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(
    caches.open(CACHE).then((cache) =>
      cache.match(e.request, { ignoreSearch: true }).then((cached) => {
        if (cached) return cached;
        return fetch(e.request).then((res) => {
          if (res && res.ok) cache.put(e.request, res.clone());
          return res;
        });
      })
    )
  );
});
""" % (version, shell)

with open(os.path.join(ROOT, "sw.js"), "w") as fh:
    fh.write(sw)
print("sw.js written:", version, "(%d files precached)" % len(files))
